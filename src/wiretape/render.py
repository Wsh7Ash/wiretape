"""Deterministic SKILL.md rendering and pack building.

``build_pack`` is the single writer of generated artifacts: it renders every
skill, writes ``pack.json`` (with a SHA-256 per skill file) and the
``results/`` report files. Tests compare committed files against a fresh
render, so the checked-in corpus can never drift from the source of truth.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

from .model import Skill


def render_description(skill: Skill) -> str:
    """Front-matter description: summary plus an explicit use-when clause."""
    summary = skill.summary.rstrip(".")
    return f"{summary}. Use when {skill.use_when}"


def render_frontmatter(pack: dict[str, Any], skill: Skill) -> str:
    lines = [
        "---",
        f"name: {skill.slug}",
        f"description: {json.dumps(render_description(skill), ensure_ascii=False)}",
        f"pack: {pack['name']}",
        f"version: {pack['version']}",
        f"category: {pack['category']}",
        "tags: [" + ", ".join(skill.tags) + "]",
        "---",
    ]
    return "\n".join(lines)


def render_skill(pack: dict[str, Any], skill: Skill) -> str:
    """Render one SKILL.md. Pure function: same input, byte-identical output."""
    body: list[str] = [f"# {skill.title}", "", f"> {skill.summary}", ""]
    body.append(f"**Use when:** {skill.use_when}")
    body.append("")
    body.append(f"**Avoid when:** {skill.avoid_when}")
    body.append("")

    body.append("## Procedure")
    body.append("")
    body.extend(f"{i}. {step}" for i, step in enumerate(skill.steps, start=1))
    body.append("")

    body.append("## Signals")
    body.append("")
    body.extend(f"- {signal}" for signal in skill.signals)
    body.append("")

    body.append("## Patterns")
    body.append("")
    for index, (label, code) in enumerate(skill.patterns, start=1):
        body.append(f"**{index}. {label}**")
        body.append("")
        body.append("```text")
        body.append(code)
        body.append("```")
        body.append("")

    body.append("## Pitfalls")
    body.append("")
    body.extend(f"- {pitfall}" for pitfall in skill.pitfalls)
    body.append("")

    body.append("## Done when")
    body.append("")
    body.extend(f"- {item}" for item in skill.done_when)
    body.append("")

    body.append("## References")
    body.append("")
    body.extend(f"- {ref}" for ref in skill.refs)

    return render_frontmatter(pack, skill) + "\n\n" + "\n".join(body) + "\n"


def strip_frontmatter(text: str) -> str:
    """Return the markdown body without the YAML front-matter block."""
    if not text.startswith("---\n"):
        return text
    end = text.find("\n---\n", 4)
    if end == -1:
        return text
    return text[end + len("\n---\n") :]


def word_count(text: str) -> int:
    return len(strip_frontmatter(text).split())


def sha256_of(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def render_catalog(pack: dict[str, Any], skills: list[Skill]) -> str:
    lines = [
        f"# {pack['name']} skill catalog",
        "",
        f"{len(skills)} skills, generated by `{pack['name']} build`.",
        "",
        "| # | Skill | Title | Tags |",
        "|---|---|---|---|",
    ]
    for index, skill in enumerate(skills, start=1):
        lines.append(
            f"| {index} | `{skill.slug}` | {skill.title} | {', '.join(skill.tags)} |"
        )
    lines.append("")
    return "\n".join(lines)


def build_pack(root: Path, pack: dict[str, Any], skills: list[Skill]) -> dict[str, str]:
    """Write skills/, pack.json and results/. Returns {relpath: sha256}."""
    written: dict[str, str] = {}
    skills_dir = root / "skills"
    skills_dir.mkdir(parents=True, exist_ok=True)

    manifest: dict[str, Any] = {
        "name": pack["name"],
        "version": pack["version"],
        "category": pack["category"],
        "license": pack.get("license", "MIT"),
        "runtime": pack["runtime"],
        "description": pack["description"],
        "skill_count": len(skills),
        "skills": [],
    }

    for skill in skills:
        rel = f"skills/{skill.slug}/SKILL.md"
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        text = render_skill(pack, skill)
        path.write_text(text, encoding="utf-8", newline="\n")
        digest = sha256_of(text)
        written[rel] = digest
        manifest["skills"].append(
            {
                "slug": skill.slug,
                "title": skill.title,
                "path": rel,
                "tags": list(skill.tags),
                **{f"meta_{k}": v for k, v in sorted(skill.meta.items())},
                "sha256": digest,
            }
        )

    pack_json = json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"
    (root / "pack.json").write_text(pack_json, encoding="utf-8", newline="\n")
    written["pack.json"] = sha256_of(pack_json)

    results = root / "results"
    results.mkdir(parents=True, exist_ok=True)
    catalog = render_catalog(pack, skills)
    (results / "catalog.md").write_text(catalog, encoding="utf-8", newline="\n")
    written["results/catalog.md"] = sha256_of(catalog)

    return written